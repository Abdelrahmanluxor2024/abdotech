        const titleEl = card.querySelector('h3');
        const textEl = card.querySelector('p');
        if (titleEl && t.about[key + 'Title']) titleEl.textContent = t.about[key + 'Title'];
        if (textEl && t.about[key + 'Text']) textEl.textContent = t.about[key + 'Text'];
